"""Verify Corollary 7.2 (phase-gap identity) on the WAND robustness panel.

For each of the 8 WAND-style parameter combinations (Chen Section 9.4),
compute the fitted phase-wise scaled-error constants A_0 (even phase)
and A_1 (odd phase) from large-n GCRR-GC data, then compare the
empirical gap A_1 - A_0 with the closed-form prediction from
Corollary 7.2:

    A_1 - A_0 = (1/2) * S_0 * phi(d_1) * sigma * sqrt(T).

The fitting procedure here is the simple large-n mean of scaled errors:
    A_eta_hat = mean(n_eff * (C_n - C_BS)) over n_eff >= 1000.

This works because the subleading O(1/sqrt(n)) term has decayed
sufficiently by n = 1000 that the mean is dominated by the limiting
constant. Alternative fits (linear in 1/sqrt(n)) yield essentially
identical results at this n range.

Inputs:  data/wand_results.csv (generated by wand_robustness_data.py).
Outputs: prints a per-case comparison table to stdout. The same
         computation will be the core of the Table 2 generation script.

Expected behavior: empirical gap matches the prediction to within
~1e-4 across all 8 cases (verified at time of writing).
"""
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import norm


# --- Configuration ---
LARGE_N_THRESHOLD = 1000  # n_eff >= this used for asymptotic fitting
INPUT_CSV = Path(__file__).parent.parent / "data" / "wand_results.csv"


def phase_gap_prediction(S: float, K: float, T: float, r: float, sigma: float) -> float:
    """Closed-form prediction of A_1 - A_0 from Corollary 7.2."""
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    return 0.5 * S * norm.pdf(d1) * sigma * np.sqrt(T)


def main():
    df = pd.read_csv(INPUT_CSV)
    gc = df[df["scheme"] == "gcrr_gc"]

    if gc.empty:
        raise RuntimeError("No GCRR-GC rows found in WAND results CSV.")

    print("Corollary 7.2 verification on WAND panel")
    print(f"  Fitting method: mean of scaled errors at n_eff >= {LARGE_N_THRESHOLD}")
    print()
    print(f'{"case":>4}  {"K":>5}  {"sigma":>5}  {"T":>5}  '
          f'{"A_0_hat":>10}  {"A_1_hat":>10}  {"emp_gap":>10}  '
          f'{"predicted":>11}  {"|diff|":>10}')
    print("-" * 90)

    max_residual = 0.0
    for case_id in sorted(gc["case_id"].unique()):
        case = gc[gc["case_id"] == case_id]
        K = case["K"].iloc[0]
        sigma = case["sigma"].iloc[0]
        T = case["T"].iloc[0]
        S = case["S"].iloc[0]
        r = case["r"].iloc[0]

        large_n = case[case["n_eff"] >= LARGE_N_THRESHOLD]
        A_0 = large_n[large_n["eta"] == 0]["scaled_error"].mean()
        A_1 = large_n[large_n["eta"] == 1]["scaled_error"].mean()
        emp_gap = A_1 - A_0

        prediction = phase_gap_prediction(S, K, T, r, sigma)
        residual = abs(emp_gap - prediction)
        max_residual = max(max_residual, residual)

        print(f"{case_id:>4}  {K:>5.1f}  {sigma:>5.2f}  {T:>5.2f}  "
              f"{A_0:>+10.4f}  {A_1:>+10.4f}  {emp_gap:>+10.4f}  "
              f"{prediction:>+11.4f}  {residual:>10.2e}")

    print()
    print(f"Maximum residual across 8 cases: {max_residual:.2e}")
    if max_residual < 1e-3:
        print("PASS: empirical phase gap matches Corollary 7.2 to "
              "within 1e-3 across all cases.")
    else:
        print("WARNING: residuals larger than expected; check fitting or data.")


if __name__ == "__main__":
    main()
